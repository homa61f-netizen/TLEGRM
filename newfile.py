    async def _استخراج_بجلسة(self, اسم_الجلسة, رابط, حد):
        نتيجة = {"جديد": 0, "اجمالي": 0, "حالة": "نجح"}
        
        عميل = await self.مدير.الحصول_على_عميل(اسم_الجلسة)
        if not عميل:
            نتيجة["حالة"] = "فشل الاتصال"
            return نتيجة
        
        try:
            كيان, خطأ = await الحصول_على_كيان(عميل, رابط)
            
            if not كيان:
                طباعة_خطأ(f"لا يمكن الوصول: {خطأ}")
                نتيجة["حالة"] = f"فشل: {str(خطأ)[:30]}"
                return نتيجة
            
            عنوان = getattr(كيان, "title", str(رابط))
            طباعة_نجاح(f"📌 {عنوان}")
            
            اعضاء = []
            عدد = 0
            
            طباعة_معلومة("📊 جاري الاستخراج...")
            
            async for عضو in عميل.iter_participants(كيان, limit=حد):
                if عضو.bot or عضو.deleted:
                    continue
                
                اعضاء.append(f"{عضو.id}:{عضو.access_hash}")
                عدد += 1
                
                if عدد % 100 == 0:
                    print(f"  ⏳ {عدد} عضو...")
            
            نتيجة["اجمالي"] = len(اعضاء)
            
            جديد = self._حفظ_الاعضاء(اسم_الجلسة, اعضاء)
            نتيجة["جديد"] = جديد
            
            طباعة_نجاح(f"✅ إجمالي: {len(اعضاء)} | جديد: {جديد}")
            
            self.سجل.info(f"استخراج {len(اعضاء)} ({جديد} جديد) من {رابط} عبر {اسم_الجلسة}")
        
        except FloodWaitError as خطأ:
            وقت = خطأ.seconds + 10
            طباعة_تحذير(f"⏳ Flood: انتظار {وقت} ثانية")
            await asyncio.sleep(وقت)
            نتيجة["حالة"] = "Flood"
        
        except Exception as خطأ:
            طباعة_خطأ(f"خطأ: {خطأ}")
            self.سجل.error(f"خطأ استخراج: {خطأ}")
            نتيجة["حالة"] = f"خطأ: {str(خطأ)[:30]}"
        
        finally:
            await عميل.disconnect()
        
        return نتيجة
    
    def _حفظ_الاعضاء(self, اسم_الجلسة, اعضاء):
        مسار = الاعدادات.مجلد_الاعضاء / f"{اسم_الجلسة}.txt"
        
        موجودين = set()
        if مسار.exists():
            with open(مسار, "r", encoding="utf-8") as م:
                for سطر in م:
                    if ":" in سطر:
                        موجودين.add(سطر.strip().split(":")[0])
        
        جديد = []
        for عضو in اعضاء:
            معرف = عضو.split(":")[0]
            if معرف not in موجودين:
                جديد.append(عضو)
                موجودين.add(معرف)
        
        if جديد:
            with open(مسار, "a", encoding="utf-8") as م:
                if مسار.stat().st_size > 0:
                    م.write("\n")
                م.write("\n".join(جديد))
        
        سجل_المسار = الاعدادات.مجلد_الاعضاء / f"{اسم_الجلسة}_سجل.txt"
        with open(سجل_المسار, "a", encoding="utf-8") as م:
            م.write(f"{datetime.now()} | استخراج | جديد: {len(جديد)} | إجمالي: {len(موجودين)}\n")
        
        return len(جديد)
    
    def _طباعة_تقرير_الاستخراج(self, نتائج, اجمالي):
        print(f"\n{'═' * 60}")
        print(f"{'📊 تقرير الاستخراج':^60}")
        print(f"{'═' * 60}\n")
        
