def استخراج_معرف_من_رابط(رابط):
    """
    استخراج المعرف من الرابط
    يرجع: (معرف, نوع) حيث نوع = "عام" أو "خاص"
    """
    رابط = رابط.strip()
    
    # رابط دعوة خاص
    if "t.me/+" in رابط:
        return رابط.split("t.me/+")[-1].split("/")[0].split("?")[0], "خاص"
    
    # رابط joinchat قديم
    if "t.me/joinchat/" in رابط:
        return رابط.split("t.me/joinchat/")[-1].split("/")[0].split("?")[0], "خاص"
    
    # رابط عام
    if "t.me/" in رابط:
        return رابط.split("t.me/")[-1].split("/")[0].split("?")[0], "عام"
    
    # @username
    if رابط.startswith("@"):
        return رابط[1:], "عام"
    
    # اسم مباشر
    return رابط, "عام"


async def الحصول_على_كيان(عميل, رابط):
    """
    تحويل الرابط إلى كيان صالح
    يرجع: (كيان, خطأ)
    """
    رابط = رابط.strip()
    
    # ═══ رابط دعوة خاص ═══
    if "t.me/+" in رابط or "joinchat" in رابط:
        if "t.me/+" in رابط:
            هاش = رابط.split("t.me/+")[-1].split("/")[0].split("?")[0]
        else:
            هاش = رابط.split("joinchat/")[-1].split("/")[0].split("?")[0]
        
        # محاولة الانضمام
        try:
            نتيجة = await عميل(ImportChatInviteRequest(هاش))
            if نتيجة.chats:
                return نتيجة.chats[0], None
        except Exception as خطأ:
            رسالة = str(خطأ).lower()
            
            # مستخدم موجود بالفعل
            if "already" in رسالة or "user already" in رسالة:
                try:
                    نتيجة = await عميل(CheckChatInviteRequest(هاش))
                    if hasattr(نتيجة, "chat") and نتيجة.chat:
                        return نتيجة.chat, None
                except Exception:
                    pass
            
            # محاولة جلب الكيان بالهاش
            try:
                كيان = await عميل.get_entity(هاش)
                return كيان, None
            except Exception:
                return None, str(خطأ)
        
        return None, "فشل الوصول للرابط الخاص"
    
    # ═══ رابط عام ═══
    معرف = رابط
    if "t.me/" in معرف:
        معرف = معرف.split("t.me/")[-1].split("/")[0].split("?")[0]
    if معرف.startswith("@"):
        معرف = معرف[1:]
    
    try:
        كيان = await عميل.get_entity(معرف)
        return كيان, None
    except Exception as خطأ:
        return None, str(خطأ)


