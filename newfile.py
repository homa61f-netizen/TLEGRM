class قاعدة_البيانات:
    def __init__(self):
        self.سجل = تهيئة_السجل("قاعدة_البيانات")
    
    def مسار_الاستثناء(self, معرف_المجموعة):
        return الاعدادات.مجلد_الاستثناءات / f"استثناء_{معرف_المجموعة}.csv"
    
    def تحميل_المستثنيين(self, معرف_المجموعة):
        مسار = self.مسار_الاستثناء(معرف_المجموعة)
        مستثنيين = set()
        
        if not مسار.exists():
            with open(مسار, "w", newline="", encoding="utf-8") as م:
                كاتب = csv.writer(م)
                كاتب.writerow(["معرف_العضو", "السبب", "الجلسة", "التاريخ"])
            return مستثنيين
        
        try:
            with open(مسار, "r", encoding="utf-8") as م:
                قارئ = csv.DictReader(م)
                for صف in قارئ:
                    if صف.get("معرف_العضو"):
                        مستثنيين.add(صف["معرف_العضو"])
        except Exception as خطأ:
            self.سجل.error(f"خطأ تحميل الاستثناءات: {خطأ}")
        
        return مستثنيين
    
    def اضافة_استثناء(self, معرف_المجموعة, معرف_العضو, السبب, اسم_الجلسة):
        مسار = self.مسار_الاستثناء(معرف_المجموعة)
        
        try:
            with open(مسار, "a", newline="", encoding="utf-8") as م:
                كاتب = csv.writer(م)
                كاتب.writerow([
                    str(معرف_العضو), السبب, اسم_الجلسة,
                    datetime.now().strftime("%Y-%m-%d %H:%M:%S")
                ])
        except Exception as خطأ:
            self.سجل.error(f"خطأ إضافة استثناء: {خطأ}")
    
    def احصائيات_الاستثناء(self, معرف_المجموعة):
        مسار = self.مسار_الاستثناء(معرف_المجموعة)
        احصائيات = {}
        
        if not مسار.exists():
            return احصائيات
        
        try:
            with open(مسار, "r", encoding="utf-8") as م:
                قارئ = csv.DictReader(م)
                for صف in قارئ:
                    سبب = صف.get("السبب", "غير_معروف")
                    احصائيات[سبب] = احصائيات.get(سبب, 0) + 1
        except Exception:
            pass
        
        return احصائيات
    
    def كل_الاستثناءات(self):
        نتيجة = []
        
        for ملف in الاعدادات.مجلد_الاستثناءات.glob("استثناء_*.csv"):
            معرف = ملف.stem.replace("استثناء_", "")
            
            try:
                with open(ملف, "r", encoding="utf-8") as م:
                    صفوف = list(csv.DictReader(م))
                
                نتيجة.append({
                    "معرف_المجموعة": معرف,
                    "الاجمالي": len(صفوف),
                    "احصائيات": self.احصائيات_الاستثناء(معرف)
                })
            except Exception:
                pass
        
        return نتيجة


