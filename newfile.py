def تهيئة_السجل(اسم="البوت"):
    logger = logging.getLogger(اسم)
    
    if logger.handlers:
        return logger
    
    logger.setLevel(logging.INFO)
    
    تاريخ_اليوم = datetime.now().strftime("%Y-%m-%d")
    ملف_السجل = الاعدادات.مجلد_السجلات / f"{تاريخ_اليوم}.log"
    
    معالج_الملف = RotatingFileHandler(
        ملف_السجل, maxBytes=10*1024*1024, backupCount=10, encoding="utf-8"
    )
    معالج_الملف.setFormatter(
        logging.Formatter("%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
                          "%Y-%m-%d %H:%M:%S")
    )
    
    معالج_الكونسول = logging.StreamHandler()
    معالج_الكونسول.setFormatter(
        logging.Formatter("%(asctime)s | %(levelname)s | %(message)s")
    )
    معالج_الكونسول.setLevel(logging.WARNING)
    
    logger.addHandler(معالج_الملف)
    logger.addHandler(معالج_الكونسول)
    
    return logger


